_current_lang: str = "en"


def _detect_chinese_locale() -> str:
    """Return 'zh' if the system uses Chinese locale, otherwise 'en'."""
    try:
        loc = locale.getlocale()[0]
        if loc and "chinese" in loc.lower():
            return "zh"
    except (ValueError, AttributeError):
        pass
    try:
        import ctypes
        # Primary language ID 0x04 = LANG_CHINESE (simplified or traditional)
        lang_id = ctypes.windll.kernel32.GetUserDefaultUILanguage()
        if (lang_id & 0xFF) == 0x04:
            return "zh"
    except (OSError, ImportError, AttributeError, ValueError):
        pass
    return "en"


def init_language(lang: str = "auto") -> None:
    """Set the active language. 'auto' defers to system locale detection."""
    global _current_lang
    if lang == "auto":
        lang = _detect_chinese_locale()
    if lang not in _TRANSLATIONS:
        lang = "en"
    _current_lang = lang


def t(key: str) -> str:
    """Translate a key to the current language."""
    return _TRANSLATIONS.get(_current_lang, {}).get(
        key, _TRANSLATIONS["en"].get(key, key)
    )
