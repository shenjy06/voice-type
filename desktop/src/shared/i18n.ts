const TRANSLATIONS: Record<string, Translations> = { en, zh }

let currentLang = 'en'

/** Resolve 'auto' against an OS locale string (e.g. "zh-CN", "en-US"). */
export function detectLanguage(locale: string): 'en' | 'zh' {
  return locale && locale.toLowerCase().startsWith('zh') ? 'zh' : 'en'
}

export function setLanguage(lang: string, systemLocale = 'en-US'): void {
  currentLang = lang === 'auto' ? detectLanguage(systemLocale) : TRANSLATIONS[lang] ? lang : 'en'
}

export function getLanguage(): string {
  return currentLang
}

export function format(template: string, params: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(params[key] ?? ''))
}

export function t(key: string): string {
  return TRANSLATIONS[currentLang]?.[key] ?? en[key] ?? key
}
